from collections.abc import Callable
from typing import Any

from alembic import command
from alembic.config import Config
from alembic.util import AutogenerateDiffsDetected
from sqlalchemy import Connection, text
from sqlalchemy.ext.asyncio import AsyncConnection, AsyncEngine


# alembic check runs env.py, so the comparison applies its name filter.
def _differences(
    connection: Connection, *, alembic_config: Callable[[Connection], Config]
) -> list[tuple[Any, ...]]:
    try:
        command.check(alembic_config(connection))
    except AutogenerateDiffsDetected as error:
        return error.diffs
    return []


def _downgrade(
    connection: Connection,
    *,
    alembic_config: Callable[[Connection], Config],
    revision: str,
) -> None:
    command.downgrade(alembic_config(connection), revision)


async def _procrastinate_objects(connection: AsyncConnection) -> list[str]:
    names = await connection.execute(
        text(
            "SELECT relname FROM pg_class WHERE relname LIKE '%procrastinate%'"
            " UNION ALL"
            " SELECT proname FROM pg_proc WHERE proname LIKE '%procrastinate%'"
            " UNION ALL"
            " SELECT typname FROM pg_type WHERE typname LIKE '%procrastinate%'"
        )
    )
    return list(names.scalars())


async def test_the_migrations_create_every_table_of_the_models(
    engine: AsyncEngine, alembic_config: Callable[[Connection], Config]
) -> None:
    async with engine.connect() as connection:
        differences = await connection.run_sync(
            _differences, alembic_config=alembic_config
        )

    assert differences == []


async def test_the_migrations_create_the_procrastinate_tables(
    engine: AsyncEngine,
) -> None:
    async with engine.connect() as connection:
        tables = (
            await connection.execute(
                text(
                    "SELECT tablename FROM pg_tables"
                    " WHERE starts_with(tablename, 'procrastinate_')"
                    " ORDER BY tablename"
                )
            )
        ).scalars()

    assert list(tables) == [
        "procrastinate_events",
        "procrastinate_jobs",
        "procrastinate_periodic_defers",
        "procrastinate_workers",
    ]


async def test_the_downgrade_drops_every_procrastinate_object(
    connection: AsyncConnection, alembic_config: Callable[[Connection], Config]
) -> None:
    before = await _procrastinate_objects(connection)
    await connection.run_sync(
        _downgrade, alembic_config=alembic_config, revision="28117bc4ee16-1"
    )
    after = await _procrastinate_objects(connection)

    # A table, a function, and a type prove that the query reads each catalog.
    assert {
        "procrastinate_jobs",
        "procrastinate_fetch_job_v2",
        "procrastinate_job_status",
    } <= set(before)
    assert after == []


async def test_the_ids_and_the_foreign_key_are_bigint(engine: AsyncEngine) -> None:
    async with engine.connect() as connection:
        columns = (
            await connection.execute(
                text(
                    "SELECT table_name, column_name, data_type, is_identity"
                    " FROM information_schema.columns"
                    " WHERE (table_name, column_name) IN"
                    " (('auth_user', 'id'), ('auth_session', 'id'),"
                    " ('auth_session', 'user_id'))"
                    " ORDER BY table_name, column_name"
                )
            )
        ).all()

    assert [tuple(column) for column in columns] == [
        ("auth_session", "id", "bigint", "YES"),
        ("auth_session", "user_id", "bigint", "NO"),
        ("auth_user", "id", "bigint", "YES"),
    ]


async def test_the_session_table_stores_the_hashed_token(engine: AsyncEngine) -> None:
    async with engine.connect() as connection:
        columns = (
            await connection.execute(
                text(
                    "SELECT column_name FROM information_schema.columns"
                    " WHERE table_name = 'auth_session' ORDER BY ordinal_position"
                )
            )
        ).scalars()

    assert list(columns) == [
        "id",
        "user_id",
        "hashed_token",
        "created_at",
        "updated_at",
        "expires_at",
    ]
